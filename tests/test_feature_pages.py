"""docs/index.html and docs/index-ko.html: the hand-maintained my-agent feature pages."""
import re
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
README_URL = 'https://github.com/hamin-apple/my-plugins#readme'


def read(name: str) -> str:
    return (REPO / 'docs' / name).read_text(encoding='utf-8')


def block(page: str, tag: str) -> str:
    m = re.search(r'<%s\b.*?</%s>' % (tag, tag), page, re.S)
    assert m, 'no <%s> block' % tag
    return m.group(0)


class KoreanFeaturePage(unittest.TestCase):
    def setUp(self):
        self.page = read('index-ko.html')

    def test_language(self):
        self.assertIn('<html lang="ko">', self.page)

    def test_header_links(self):
        header = block(self.page, 'header')
        self.assertIn('href="index.html"', header)
        self.assertIn('href="architecture.html"', header)

    def test_offline(self):
        for bad in ('<link ', 'src=', '@import', 'url(http'):
            self.assertNotIn(bad, self.page)

    def test_hand_maintained(self):
        self.assertNotIn('Generated by tools/build-docs.py', self.page)

    def test_noscript_note(self):
        note = block(self.page, 'noscript')
        self.assertIn(README_URL, note)
        self.assertNotIn('my-agent-features.md', note)


